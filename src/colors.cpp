// ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
//  COLOR PALETTE (Variable Definitions)
// ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
uint16_t colSky1, colSky2, colSky3;
uint16_t colGrassL, colGrassD;
uint16_t colRoadL, colRoadD;
uint16_t colRumbleL, colRumbleD;
uint16_t colLane, colFog;

struct Palette {
  uint16_t sky1, sky2, sky3;
  uint16_t grassL, grassD;
  uint16_t roadL, roadD;
  uint16_t rumbleL, rumbleD;
  uint16_t lane, fog;
};

// ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
//  FUNCTION IMPLEMENTATION
// ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

uint16_t rgb(uint8_t r, uint8_t g, uint8_t b) {
  return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3);
}

uint16_t darkenCol(uint16_t c, float f) {
  int r = (int)(((c >> 11) & 0x1F) * f);
  int g = (int)(((c >> 5)  & 0x3F) * f);
  int b = (int)((c & 0x1F) * f);
  return ((r & 0x1F) << 11) | ((g & 0x3F) << 5) | (b & 0x1F);
}

uint16_t lerpCol(uint16_t c1, uint16_t c2, float t) {
  if (t <= 0) return c1;
  if (t >= 1) return c2;
  int r1 = (c1 >> 11) & 0x1F, g1 = (c1 >> 5) & 0x3F, b1 = c1 & 0x1F;
  int r2 = (c2 >> 11) & 0x1F, g2 = (c2 >> 5) & 0x3F, b2 = c2 & 0x1F;
  return (((int)(r1 + (r2 - r1) * t) & 0x1F) << 11) |
         (((int)(g1 + (g2 - g1) * t) & 0x3F) << 5)  |
          ((int)(b1 + (b2 - b1) * t) & 0x1F);
}

static Palette getPalette(int timeOfDay) {
  Palette p;
  switch (timeOfDay) {
    case 0: // Day
      p.sky1 = rgb(115, 185, 255);
      p.sky2 = rgb(80, 140, 230);
      p.sky3 = rgb(50, 100, 200);
      p.grassL = rgb(16, 200, 16);
      p.grassD = rgb(0, 154, 0);
      p.roadL = rgb(107, 107, 107);
      p.roadD = rgb(105, 105, 105);
      p.rumbleL = TFT_WHITE;
      p.rumbleD = TFT_RED;
      p.lane = rgb(204, 204, 204);
      p.fog = rgb(180, 215, 255);
      break;
    case 1: // Sunset
      p.sky1 = rgb(255, 140, 60);
      p.sky2 = rgb(255, 90, 30);
      p.sky3 = rgb(140, 30, 10);
      p.grassL = rgb(80, 120, 20);
      p.grassD = rgb(50, 80, 10);
      p.roadL = rgb(95, 85, 80);
      p.roadD = rgb(85, 75, 70);
      p.rumbleL = rgb(240, 200, 150);
      p.rumbleD = rgb(200, 50, 30);
      p.lane = rgb(200, 180, 140);
      p.fog = rgb(200, 120, 60);
      break;
    default: // Night
      p.sky1 = rgb(10, 15, 50);
      p.sky2 = rgb(5, 8, 30);
      p.sky3 = rgb(0, 2, 15);
      p.grassL = rgb(0, 60, 15);
      p.grassD = rgb(0, 40, 8);
      p.roadL = rgb(55, 55, 65);
      p.roadD = rgb(45, 45, 55);
      p.rumbleL = rgb(100, 100, 120);
      p.rumbleD = rgb(80, 10, 10);
      p.lane = rgb(110, 110, 130);
      p.fog = rgb(15, 15, 40);
      break;
  }
  return p;
}

void initColors(int timeOfDay) {
  blendColors(timeOfDay, timeOfDay, 0.0f);
}

void blendColors(int fromTimeOfDay, int toTimeOfDay, float t) {
  if (t < 0.0f) t = 0.0f;
  if (t > 1.0f) t = 1.0f;

  Palette a = getPalette(fromTimeOfDay);
  Palette b = getPalette(toTimeOfDay);

  colSky1 = lerpCol(a.sky1, b.sky1, t);
  colSky2 = lerpCol(a.sky2, b.sky2, t);
  colSky3 = lerpCol(a.sky3, b.sky3, t);
  colGrassL = lerpCol(a.grassL, b.grassL, t);
  colGrassD = lerpCol(a.grassD, b.grassD, t);
  colRoadL = lerpCol(a.roadL, b.roadL, t);
  colRoadD = lerpCol(a.roadD, b.roadD, t);
  colRumbleL = lerpCol(a.rumbleL, b.rumbleL, t);
  colRumbleD = lerpCol(a.rumbleD, b.rumbleD, t);
  colLane = lerpCol(a.lane, b.lane, t);
  colFog = lerpCol(a.fog, b.fog, t);
}

